def _points(piece, n_per_unit=40):
    kind = piece[0]
    if kind == L_:
        _, x0, y0, x1, y1 = piece
        return [(x0, y0), (x1, y1)]
    if kind == A_:
        _, cx, cy, rx, ry, st, sw = piece
        n = max(8, int(abs(sw) / 360 * 2 * math.pi * max(rx, ry) * n_per_unit))
        return [(cx + rx * math.cos(math.radians(st + sw * i / n)),
                 cy + ry * math.sin(math.radians(st + sw * i / n))) for i in range(n + 1)]
    raise ValueError(kind)


def polylines(ch):
    """[(points, is_dot)] per stroke, joined into one continuous polyline."""
    out = []
    for stroke in LETTERS[ch]:
        if stroke[0][0] == D_:
            out.append(([stroke[0][1:]], True)); continue
        pts = []
        for piece in stroke:
            p = _points(piece)
            pts += p[1:] if pts else p
        out.append((pts, False))
    return out


def bounds(ch):
    xs = [x for pts, _ in polylines(ch) for x, _ in pts]
    return min(xs), max(xs)


def width(ch):
    if ch == " ":
        return 0.7
    lo, hi = bounds(ch)
    return hi                    # letters start at x=0 (all drawn from x>=0)


def word_width(word, gap):
    return sum(width(ch) for ch in word) + gap * (len(word) - 1)
